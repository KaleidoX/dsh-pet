/// Metadata version written by `cargo xtask anim-meta`.
const ANIM_META_VERSION: u32 = 1;
/// Column names of a serialized [`Frame`], in order.
const ANIM_META_FIELDS: [&str; 7] = ["t", "mask", "body", "head", "feet", "bias", "rgb"];

/// Per-clip pose metadata for pose-matched hard cuts.
///
/// Generated offline from the WebM clips and loaded next to the assets. Every
/// value is an integer (microseconds, thousandths, masked bits) so the file is
/// compact and regenerating it produces identical bytes.
#[derive(Debug, Clone, Default, Deserialize, Serialize)]
pub struct AnimMeta {
    #[serde(default)]
    pub clips: BTreeMap<String, ClipMeta>,
}

/// Frame count, duration, the entry window and the final frame of one clip.
#[derive(Debug, Clone, Deserialize, Serialize)]
pub struct ClipMeta {
    /// Frames the clip decodes to.
    pub frames: u32,
    /// Clip duration in microseconds.
    pub duration_us: u32,
    /// The frames a clip may be entered at, from frame 0 on.
    pub entry: Vec<Frame>,
    /// The frame a natural end leaves on screen.
    pub last: Frame,
}

/// One frame as stored on disk: a 7-tuple in the order of [`ANIM_META_FIELDS`].
pub type FrameRepr = (u32, Mask, [u16; 2], [u16; 2], u16, i16, [u8; 3]);

/// One candidate frame: when it is shown and what the pet looks like there.
#[derive(Debug, Clone, Deserialize, Serialize)]
#[serde(from = "FrameRepr", into = "FrameRepr")]
pub struct Frame {
    /// Presentation time relative to the clip's first frame, microseconds.
    pub t: u32,
    pub pose: Pose,
}

impl From<FrameRepr> for Frame {
    fn from((t, mask, body, head, feet, bias, rgb): FrameRepr) -> Self {
        Self { t, pose: Pose { mask, body: body.map(milli), head: head.map(milli), feet: milli(feet), bias: f32::from(bias) / 1000.0, rgb } }
    }
}

impl From<Frame> for FrameRepr {
    fn from(frame: Frame) -> Self {
        let pose = frame.pose;
        (
            frame.t,
            pose.mask,
            pose.body.map(thousandths),
            pose.head.map(thousandths),
            thousandths(pose.feet),
            (pose.bias * 1000.0).round() as i16,
            pose.rgb,
        )
    }
}

/// Thousandths to a ratio.
fn milli(value: u16) -> f32 {
    f32::from(value) / 1000.0
}

/// Ratio to thousandths, clamped to the stored range (costs and positions are
/// ratios in `0..=1`; only an out-of-range pose could exceed it).
fn thousandths(value: f32) -> u16 {
    (value * 1000.0).round().clamp(0.0, 1000.0) as u16
}

/// Appearance of the pet in one frame, at the descriptor grid's resolution.
///
/// Positions are normalised to `0..=1` over the canvas, so the descriptor does
/// not depend on the clip resolution. A fully transparent frame is all zeros.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct Pose {
    /// Opaque cells, one bit per cell, [`GRID_H`] rows of [`GRID_W`] bits.
    pub mask: Mask,
    /// Centre of mass of the opaque pixels, x right / y down.
    pub body: [f32; 2],
    /// Same, restricted to the top quarter of the silhouette.
    pub head: [f32; 2],
    /// Lowest opaque row.
    pub feet: f32,
    /// `(right - left) / total` opaque pixels: which way the body leans.
    pub bias: f32,
    /// Mean colour of the opaque pixels.
    pub rgb: [u8; 3],
}

impl Pose {
    /// Whether nothing opaque was found (an all-transparent frame).
    pub fn is_empty(&self) -> bool {
        self.mask.0.iter().all(|row| *row == 0)
    }
}

/// The silhouette mask: one [`u32`] per grid row, bit `x` set when the cell is
/// opaque. Serialized as a hex string of [`GRID_H`] 8-digit groups.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Mask(pub [u32; GRID_H]);

impl Mask {
    /// The mask as [`GRID_H`] 8-digit hex groups, one per row.
    pub fn to_hex(&self) -> String {
        let mut text = String::with_capacity(GRID_H * 8);
        for row in &self.0 {
            text.push_str(&format!("{row:08x}"));
        }
        text
    }
}

impl Serialize for Mask {
    fn serialize<S: Serializer>(&self, serializer: S) -> std::result::Result<S::Ok, S::Error> {
        serializer.serialize_str(&self.to_hex())
    }
}

impl<'de> Deserialize<'de> for Mask {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> std::result::Result<Self, D::Error> {
        let text = String::deserialize(deserializer)?;
        if text.len() != GRID_H * 8 {
            return Err(D::Error::custom(format!("mask must be {} hex digits, got {}", GRID_H * 8, text.len())));
        }
        let mut rows = [0u32; GRID_H];
        for (row, chunk) in rows.iter_mut().zip(text.as_bytes().chunks_exact(8)) {
            let chunk = std::str::from_utf8(chunk).map_err(|_| D::Error::custom("mask is not ASCII"))?;
            *row = u32::from_str_radix(chunk, 16).map_err(|_| D::Error::custom(format!("mask row {chunk:?} is not hex")))?;
        }
        Ok(Self(rows))
    }
}

/// The on-disk document: a versioned, self-describing wrapper around the
/// clips. `cargo xtask anim-meta` writes it; the app only ever reads it.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AnimMetaDoc {
    version: u32,
    grid: [usize; 2],
    fields: Vec<String>,
    #[serde(flatten)]
    pub meta: AnimMeta,
}

/// Writes one frame as the 7-tuple documented in [`ANIM_META_FIELDS`]: `t`,
/// mask, body, head, feet, bias, rgb.
fn write_frame(out: &mut String, frame: &Frame) {
    let repr: FrameRepr = frame.clone().into();
    let (t, mask, body, head, feet, bias, rgb) = repr;
    out.push_str(&format!(
        "[{t}, {}, [{}, {}], [{}, {}], {feet}, {bias}, [{}, {}, {}]]",
        json_string(&mask.to_hex()),
        body[0],
        body[1],
        head[0],
        head[1],
        rgb[0],
        rgb[1],
        rgb[2],
    ));
}

/// Quoted JSON string. Clip names are the only free-form text in the file.
fn json_string(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for ch in text.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            ch if (ch as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", ch as u32)),
            ch => out.push(ch),
        }
    }
    out.push('"');
    out
}

impl AnimMetaDoc {
    /// Wraps freshly generated metadata with the current version and layout.
    pub fn new(meta: AnimMeta) -> Self {
        Self { version: ANIM_META_VERSION, grid: [GRID_W, GRID_H], fields: ANIM_META_FIELDS.iter().map(|field| (*field).to_owned()).collect(), meta }
    }

    /// The document as JSON, one frame per line.
    ///
    /// Written by hand rather than through the pretty printer: a frame is a
    /// 7-tuple that reads well on one line, and per-value line breaks would
    /// double the file size. Keys come from a `BTreeMap`, so the bytes are
    /// identical across runs.
    pub fn to_json(&self) -> String {
        let mut out = String::new();
        out.push_str("{\n");
        out.push_str(&format!("  \"version\": {},\n  \"grid\": [{}, {}],\n", self.version, self.grid[0], self.grid[1]));
        out.push_str("  \"fields\": [");
        for (index, field) in self.fields.iter().enumerate() {
            if index > 0 {
                out.push_str(", ");
            }
            out.push_str(&json_string(field));
        }
        out.push_str("],\n  \"clips\": {");
        for (index, (name, clip)) in self.meta.clips.iter().enumerate() {
            out.push_str(if index == 0 { "\n" } else { ",\n" });
            out.push_str(&format!(
                "    {}: {{\n      \"frames\": {},\n      \"duration_us\": {},\n      \"entry\": [\n",
                json_string(name),
                clip.frames,
                clip.duration_us
            ));
            for (frame_index, frame) in clip.entry.iter().enumerate() {
                out.push_str("        ");
                write_frame(&mut out, frame);
                out.push_str(if frame_index + 1 == clip.entry.len() { "\n" } else { ",\n" });
            }
            out.push_str("      ],\n      \"last\": ");
            write_frame(&mut out, &clip.last);
            out.push_str("\n    }");
        }
        out.push_str("\n  }\n}\n");
        out
    }

    /// Checks the document layout: version, grid and column names.
    ///
    /// Per-clip problems are not fatal: [`AnimMeta::load`] drops the offending
    /// clip and keeps the rest, so one bad clip cannot disable pose matching for
    /// every other clip.
    fn validate(&self) -> std::result::Result<(), String> {
        if self.version != ANIM_META_VERSION {
            return Err(format!("version {} is not {ANIM_META_VERSION}; run `cargo xtask anim-meta`", self.version));
        }
        if self.grid != [GRID_W, GRID_H] {
            return Err(format!("descriptor grid {:?} is not [{GRID_W}, {GRID_H}]; run `cargo xtask anim-meta`", self.grid));
        }
        let fields = self.fields.iter().map(String::as_str).collect::<Vec<_>>();
        if fields != ANIM_META_FIELDS {
            return Err(format!("fields {fields:?} are not {ANIM_META_FIELDS:?}; run `cargo xtask anim-meta`"));
        }
        Ok(())
    }
}

impl ClipMeta {
    /// Checks the invariants `entry_frame` and the decoder rely on.
    ///
    /// `entry[0]` must be frame 0 itself, the window cannot be longer than the
    /// clip, and both the window and the last frame must fit in the declared
    /// duration; a stale metadata file could otherwise name a frame the clip
    /// does not have.
    fn validate(&self) -> std::result::Result<(), String> {
        if self.frames == 0 {
            return Err("clip has zero frames".to_owned());
        }
        if self.entry.is_empty() {
            return Err("clip has an empty entry window".to_owned());
        }
        if self.entry[0].t != 0 {
            return Err(format!("entry window starts at {} us, not frame 0", self.entry[0].t));
        }
        if self.entry.windows(2).any(|pair| pair[1].t < pair[0].t) {
            return Err("entry frames are out of order".to_owned());
        }
        if self.entry.len() > self.frames as usize {
            return Err(format!("entry window has {} frames but the clip has {}", self.entry.len(), self.frames));
        }
        if self.last.t < self.entry[self.entry.len() - 1].t || self.last.t > self.duration_us {
            return Err(format!("last frame at {} us does not fit the window and duration {} us", self.last.t, self.duration_us));
        }
        Ok(())
    }
}

impl AnimMeta {
    /// Loads `anim-meta.json` from an asset root.
    ///
    /// The file is optional: clips without metadata are entered at frame 0.
    /// A missing, unreadable or stale file logs a warning and yields `None`
    /// instead of failing startup.
    pub fn load(asset_dir: &Path) -> Option<Self> {
        let path = asset_dir.join(ANIM_META_FILE);
        let text = match std::fs::read_to_string(&path) {
            Ok(text) => text,
            Err(err) => {
                log::warn!("{}: {err}; animations enter at frame 0", path.display());
                return None;
            }
        };
        match serde_json_lenient::from_str::<AnimMetaDoc>(&text) {
            Ok(doc) => {
                if let Err(reason) = doc.validate() {
                    log::warn!("{}: {reason}; animations enter at frame 0", path.display());
                    return None;
                }
                let mut meta = doc.meta;
                // A clip whose record is inconsistent is dropped on its own:
                // the rest of the file is still usable.
                meta.clips.retain(|name, clip| match clip.validate() {
                    Ok(()) => true,
                    Err(reason) => {
                        log::warn!("{}: dropping clip {name:?}: {reason}", path.display());
                        false
                    }
                });
                log::info!("pose metadata: {} clips from {}", meta.clips.len(), path.display());
                Some(meta)
            }
            Err(err) => {
                log::warn!("{}: {err}; animations enter at frame 0", path.display());
                None
            }
        }
    }

    /// The last frame's pose of `clip`, for matching against an entry window.
    pub fn last_pose(&self, clip: &str) -> Option<&Pose> {
        self.clips.get(clip).map(|meta| &meta.last.pose)
    }

    /// The entry window of `clip`.
    pub fn entry(&self, clip: &str) -> Option<&[Frame]> {
        self.clips.get(clip).map(|meta| meta.entry.as_slice())
    }
}
